package main

import (
	"crypto/ecdh"
	"crypto/sha256"
	"encoding/base64"
	"fmt"
	"strconv"
)

func init() { register(methodWireGuard) }

// WireGuard in the kernel (Linux 5.6+; older kernels need wireguard-dkms): one UDP port, no
// daemon. The panel makes both key pairs and a preshared key once (stored per tunnel, like
// the IPsec keys), writes each side's config and loads it with `wg setconf` — no wg-quick,
// so nothing touches the host's routes or DNS. One side dials (endpoint + keepalive), the
// other only listens; the interface carries private IPv4 for port forwarding, like GRE.
var methodWireGuard = &Method{
	ID:       "wg",
	Title:    "WireGuard",
	Desc:     "Kernel WireGuard over UDP: encrypted, fast, no daemon. Keys are generated by the panel. Needs UDP open on the route (Iran's DPI drops WireGuard on some routes — the benchmark shows it).",
	Families: []string{"v4", "v6"},
	Encrypt:  "ChaCha20-Poly1305",
	Fields: []Field{
		{Key: "mtu", Label: "Tunnel MTU", Type: "number", Default: "1380"},
		{Key: "port", Label: "UDP port (blank = per-tunnel default)", Type: "number", Default: ""},
		{Key: "dialer", Label: "Who connects (the other side only listens)", Type: "select", Default: "iran", Options: []string{"iran", "foreign"}},
		{Key: "keepalive", Label: "Keepalive (seconds)", Type: "number", Default: "25", Advanced: true},
	},
	// a route that drops UDP started from Iran may pass it started from abroad; a smaller
	// MTU gets bulk data through where pings pass but full packets don't
	Alts: func(string) []map[string]string {
		return []map[string]string{{"dialer": "foreign"}, {"mtu": "1280"}}
	},
	Build: func(c *buildCtx) (ir, kh SidePlan, err error) {
		d := c.D
		port, err := wgPort(c)
		if err != nil {
			return ir, kh, err
		}
		if _, err := strconv.Atoi(c.Opt("keepalive")); err != nil {
			return ir, kh, fmt.Errorf("WireGuard: keepalive must be a number of seconds")
		}
		irPriv, irPub := wgKey(c.T.secret("wg-ir"))
		khPriv, khPub := wgKey(c.T.secret("wg-kh"))
		psk, _ := wgKey(c.T.secret("wg-psk"))
		irDials := c.Opt("dialer") != "foreign"

		dir := tunnelDir(c.T)
		conf := dir + "/wg.conf"
		cfg := func(priv, peerPub, peerAddr string, dials bool) FileSpec {
			s := fmt.Sprintf("[Interface]\nPrivateKey = %s\nListenPort = %d\n\n[Peer]\nPublicKey = %s\nPresharedKey = %s\nAllowedIPs = 0.0.0.0/0, ::/0\n",
				priv, port, peerPub, psk)
			if dials {
				s += fmt.Sprintf("Endpoint = %s:%d\nPersistentKeepalive = %s\n", bracket(peerAddr), port, c.Opt("keepalive"))
			}
			return FileSpec{Content: []byte(s), Mode: 0o600}
		}
		// AllowedIPs 0.0.0.0/0 only says what may come in on this one peer: `wg setconf`
		// adds no routes (wg-quick would), the /30 on the interface is all that routes into it.
		// The config goes in on a pipe: Ubuntu's AppArmor profile for wg (24.10+) lets it open
		// files only under /etc/wireguard ("fopen: Permission denied" for ours, seen on 26.04)
		up := func(self, peer string) string {
			return fmt.Sprintf(`modprobe wireguard 2>/dev/null || true
ip link add %[1]s type wireguard || { echo "this kernel has no WireGuard (Linux 5.6+, or install wireguard-dkms; not available in OpenVZ/LXC containers)"; exit 1; }
out=$(cat %[2]s | wg setconf %[1]s /dev/stdin 2>&1) || { echo "could not load the WireGuard config on UDP port %[4]d: $out"; exit 1; }
ip link set %[1]s mtu %[3]s up
`, d.Iface, conf, c.Opt("mtu"), port)
		}
		ir, kh = kernelTunnel(c, "WireGuard "+c.T.Name, up, "")
		ir.Files[conf] = cfg(irPriv, khPub, d.KHPub, irDials)
		kh.Files[conf] = cfg(khPriv, irPub, d.IRPub, !irDials)
		ir.Setup, kh.Setup = wgSetup, wgSetup
		return ir, kh, nil
	},
}

// wgPort is the UDP port both ends listen on.
func wgPort(c *buildCtx) (int, error) {
	p := c.D.BasePort + 1 // +2 is the tunnel's speed-test port (probePortFor)
	if v := c.Opt("port"); v != "" {
		n, err := strconv.Atoi(v)
		if err != nil || n < 1 || n > 65535 {
			return 0, fmt.Errorf("WireGuard: UDP port must be 1..65535")
		}
		p = n
	}
	return p, nil
}

// wgKey turns a stored secret into a Curve25519 key pair (base64, as wg reads them). The
// secret is kept, not the key, so the pair is the same on every apply.
func wgKey(secret string) (priv, pub string) {
	b := sha256.Sum256([]byte("tp-wg:" + secret))
	b[0] &= 248
	b[31] = b[31]&127 | 64
	k, err := ecdh.X25519().NewPrivateKey(b[:])
	if err != nil { // 32 bytes is always a valid X25519 key
		panic(err)
	}
	return base64.StdEncoding.EncodeToString(b[:]), base64.StdEncoding.EncodeToString(k.PublicKey().Bytes())
}

// wgSetup installs the wg tool when missing (the kernel module ships with the kernel). Setup
// runs under set -e: every step that may fail ends in || true, so a failed apt-get update
// (exit 100, seen live on netherlands-iran) reaches the check that says why.
const wgSetup = aptFix + `if ! command -v wg >/dev/null 2>&1; then
  L=/tmp/tp-wg-install.log; : >$L
  if command -v apt-get >/dev/null 2>&1; then
    tp_apt_fix || true
    export DEBIAN_FRONTEND=noninteractive
    timeout 300 apt-get install -y -qq --no-install-recommends wireguard-tools >>$L 2>&1 || {
      timeout 300 apt-get update -qq >>$L 2>&1 || true
      timeout 300 apt-get install -y -qq --no-install-recommends wireguard-tools >>$L 2>&1 || true
    }
  elif command -v dnf >/dev/null 2>&1; then
    timeout 300 dnf install -y wireguard-tools >>$L 2>&1 || true
  elif command -v yum >/dev/null 2>&1; then
    timeout 300 yum install -y wireguard-tools >>$L 2>&1 || true
  fi
  command -v wg >/dev/null 2>&1 || { echo "could not install wireguard-tools (the wg command): $(grep -E '^(E|W|Err|Error)' $L | tail -3 | tr '\n' ' ')"; exit 1; }
fi
`
